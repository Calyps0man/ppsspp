#!/bin/bash
# Builds the SPU programs and embeds them as C arrays (committed, like PS3/rsx/RSXShaders.inc):
#   PS3_SDK=/path/to/ps3dev bash PS3/spu/build.sh
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
SDK="${PS3_SDK:-${PS3DEV:-/usr/local/ps3dev}}"
CC="$SDK/spu/bin/spu-gcc"
[ -x "$CC" ] || CC="$SDK/bin/spu-gcc"
OUT="$(mktemp -d)"

# build <source.c> <output.inc> <array name>
build() {
	local src="$1" inc="$2" name="$3" elf="$OUT/$(basename "$1" .c).elf"
	"$CC" -O3 -Wall -Wextra -Wno-unused-parameter -I"$SDK/spu/include" -ffunction-sections -fdata-sections \
		"$HERE/$src" -L"$SDK/spu/lib" -lsputhread -Wl,--gc-sections -o "$elf"
	"$SDK/spu/bin/spu-strip" "$elf" 2>/dev/null || "$SDK/bin/spu-strip" "$elf" 2>/dev/null || true
	python3 - "$elf" "$HERE/$inc" "$name" "$src" <<'PY'
import sys
data = open(sys.argv[1], 'rb').read()
with open(sys.argv[2], 'w') as f:
    f.write('// Generated by PS3/spu/build.sh from PS3/spu/%s - do not edit.\n' % sys.argv[4])
    f.write('static const unsigned char %s[%d] __attribute__((aligned(128))) = {\n' % (sys.argv[3], len(data)))
    for i in range(0, len(data), 24):
        f.write('\t' + ', '.join('0x%02x' % b for b in data[i:i + 24]) + ',\n')
    f.write('};\n')
print('SPU %s: %d bytes' % (sys.argv[4], len(data)))
PY
	"$SDK/spu/bin/spu-size" "$elf" 2>/dev/null || "$SDK/bin/spu-size" "$elf" 2>/dev/null || true
}

build sasmix.c SasMixSpu.inc kSasMixSpuElf
build tlprep.c TLPrepSpu.inc kTLPrepSpuElf
build texspu.c TexSpu.inc kTexSpuElf
rm -rf "$OUT"
